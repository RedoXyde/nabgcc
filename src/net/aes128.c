static uint8_t xtime(uint8_t x)
{
	return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

/* GF(2^8) multiply, only ever called with small constants */
static uint8_t gmul(uint8_t a, uint8_t b)
{
	uint8_t p = 0;
	while(b) {
		if(b & 1) p ^= a;
		a = xtime(a);
		b >>= 1;
	}
	return p;
}

void aes128_dec_init(struct aes128_dec *ctx, const uint8_t key[16])
{
	uint8_t rcon = 0x01;
	uint32_t i;

	for(i=0;i<16;i++)
		ctx->rk[i] = key[i];
	for(i=16;i<176;i+=4) {
		uint8_t t0 = ctx->rk[i-4], t1 = ctx->rk[i-3];
		uint8_t t2 = ctx->rk[i-2], t3 = ctx->rk[i-1];
		if((i % 16) == 0) {
			uint8_t tmp = t0;   /* RotWord + SubWord + Rcon */
			t0 = (uint8_t)(aes_sbox[t1] ^ rcon);
			t1 = aes_sbox[t2];
			t2 = aes_sbox[t3];
			t3 = aes_sbox[tmp];
			rcon = xtime(rcon);
		}
		ctx->rk[i+0] = (uint8_t)(ctx->rk[i-16] ^ t0);
		ctx->rk[i+1] = (uint8_t)(ctx->rk[i-15] ^ t1);
		ctx->rk[i+2] = (uint8_t)(ctx->rk[i-14] ^ t2);
		ctx->rk[i+3] = (uint8_t)(ctx->rk[i-13] ^ t3);
	}
}

static void add_round_key(uint8_t *st, const uint8_t *rk)
{
	uint32_t i;
	for(i=0;i<16;i++)
		st[i] ^= rk[i];
}

/* State is column-major as in FIPS-197: st[r + 4c]... but a flat byte
 * array in memory order works as long as rows/columns are used
 * consistently; here st[i] is simply byte i of the block, so row r of
 * column c is st[4c + r]. */
static void inv_shift_rows(uint8_t *st)
{
	uint8_t t;
	/* row 1: right rotate by 1 */
	t = st[13]; st[13] = st[9]; st[9] = st[5]; st[5] = st[1]; st[1] = t;
	/* row 2: rotate by 2 */
	t = st[2]; st[2] = st[10]; st[10] = t;
	t = st[6]; st[6] = st[14]; st[14] = t;
	/* row 3: left rotate by 1 */
	t = st[3]; st[3] = st[7]; st[7] = st[11]; st[11] = st[15]; st[15] = t;
}

static void inv_sub_bytes(uint8_t *st)
{
	uint32_t i;
	for(i=0;i<16;i++)
		st[i] = aes_isbox[st[i]];
}

static void inv_mix_columns(uint8_t *st)
{
	uint32_t c;
	for(c=0;c<16;c+=4) {
		uint8_t a0 = st[c+0], a1 = st[c+1], a2 = st[c+2], a3 = st[c+3];
		st[c+0] = (uint8_t)(gmul(a0,14) ^ gmul(a1,11) ^ gmul(a2,13) ^ gmul(a3, 9));
		st[c+1] = (uint8_t)(gmul(a0, 9) ^ gmul(a1,14) ^ gmul(a2,11) ^ gmul(a3,13));
		st[c+2] = (uint8_t)(gmul(a0,13) ^ gmul(a1, 9) ^ gmul(a2,14) ^ gmul(a3,11));
		st[c+3] = (uint8_t)(gmul(a0,11) ^ gmul(a1,13) ^ gmul(a2, 9) ^ gmul(a3,14));
	}
}

void aes128_dec_block(const struct aes128_dec *ctx,
                      uint8_t out[16], const uint8_t in[16])
{
	uint8_t st[16];
	uint32_t i, round;

	for(i=0;i<16;i++)
		st[i] = in[i];

	add_round_key(st, &ctx->rk[160]);
	for(round=9;round>=1;round--) {
		inv_shift_rows(st);
		inv_sub_bytes(st);
		add_round_key(st, &ctx->rk[round*16]);
		inv_mix_columns(st);
	}
	inv_shift_rows(st);
	inv_sub_bytes(st);
	add_round_key(st, &ctx->rk[0]);

	for(i=0;i<16;i++)
		out[i] = st[i];
}

int32_t aes_key_unwrap(const uint8_t kek[16], const uint8_t *wrapped,
                       uint32_t wlen, uint8_t *out)
{
	struct aes128_dec ctx;
	uint8_t a[8], b[16];
	uint32_t n, i, j, t;

	if((wlen < 24) || (wlen % 8))
		return 0;
	n = wlen/8 - 1;

	aes128_dec_init(&ctx, kek);

	for(i=0;i<8;i++)
		a[i] = wrapped[i];
	for(i=0;i<n*8;i++)
		out[i] = wrapped[8+i];

	for(j=6;j-- > 0;) {
		for(i=n;i>=1;i--) {
			t = n*j + i;
			/* B = AES-1(KEK, (A ^ t) | R[i]) */
			memcpy(b, a, 8);
			b[7] ^= (uint8_t)(t);
			b[6] ^= (uint8_t)(t >> 8);
			b[5] ^= (uint8_t)(t >> 16);
			b[4] ^= (uint8_t)(t >> 24);
			memcpy(b+8, &out[(i-1)*8], 8);
			aes128_dec_block(&ctx, b, b);
			memcpy(a, b, 8);
			memcpy(&out[(i-1)*8], b+8, 8);
		}
	}

	/* RFC 3394 integrity check value */
	for(i=0;i<8;i++)
		if(a[i] != 0xa6)
			return 0;
	return 1;
}

int32_t rsn_find_gtk(const uint8_t *data, uint32_t len,
                     uint8_t *gtk, uint32_t gtk_max,
                     uint32_t *gtk_len, uint8_t *key_id)
{
	uint32_t pos = 0;

	while(pos+2 <= len) {
		uint8_t type = data[pos];
		uint8_t elen = data[pos+1];

		if(type == 0xdd && elen == 0)
			return 0;                     /* pad KDE: nothing follows */
		if(pos+2+elen > len)
			return 0;
		/* GTK KDE. The length field covers OUI(3) + data type(1) +
		 * the KDE data, and the GTK's data is a key id/tx byte, one
		 * reserved byte, then the key: klen = elen - 4 - 2. */
		if(type == 0xdd && elen > 4+2 &&
		   data[pos+2] == 0x00 && data[pos+3] == 0x0f &&
		   data[pos+4] == 0xac && data[pos+5] == 0x01) {
			uint32_t klen = (uint32_t)elen - 4 - 2;
			if(klen == 0 || klen > gtk_max)
				return 0;
			*key_id = data[pos+6] & 0x03;
			*gtk_len = klen;
			memcpy(gtk, &data[pos+8], klen);
			return 1;
		}
		pos += 2 + elen;
	}
	return 0;
}


